// ============================================================================
//  ПОДБОР ПОРОГА РЕЛЕВАНТНОСТИ  (Э7)
// ----------------------------------------------------------------------------
//  Запуск:  npm run tune
//
//  Скрипт прогоняет через индекс BM25 два набора вопросов на русском:
//    • «в базе»    — вопросы, ответ на которые ТОЧНО есть в базе знаний;
//    • «посторонние» — вопросы не по теме / без ответа в базе.
//
//  Для каждого печатается bestScore (оценка лучшего документа). Затем скрипт
//  показывает распределение обоих кластеров и рекомендует порог THRESHOLD —
//  значение в «провале» между «в базе» и «посторонними». Реальные цифры этого
//  прогона перенесены в docs/ASSISTANT.md.
// ============================================================================

import { getIndex } from "../src/lib/assistant/knowledge";

const LANG = "ru" as const;

// ~20 вопросов, ответ на которые ЕСТЬ в базе (разными словами, с синонимами).
const IN_BASE: string[] = [
  "почему мкс не падает на землю",
  "что такое орбитальная скорость",
  "чем микрогравитация отличается от отсутствия гравитации",
  "на какой высоте летает станция и зачем её поднимают",
  "откуда космонавты берут кислород",
  "как на станции очищают и повторно используют воду",
  "как космонавты едят и спят в невесомости",
  "как корабли пристыковываются к станции",
  "из каких модулей собрана мкс",
  "что такое выход в открытый космос",
  "какие опыты проводят на орбите",
  "что такое космический мусор и манёвр уклонения",
  "опасна ли радиация для экипажа",
  "когда началось строительство станции",
  "какие страны участвуют в проекте",
  "как увидеть мкс с земли и почему она яркая",
  "что такое корабль союз и crew dragon",
  "как станция связывается с землёй",
  "как стать космонавтом",
  "что такое tle",
  "что такое чёрная дыра",
  "расскажи про телескоп джеймса уэбба",
  "что такое обсерватория улугбека",
  "чем занимается гиссарская обсерватория",
];

// ~10 посторонних вопросов (нет ответа в базе / не по теме).
const OFF_TOPIC: string[] = [
  "как приготовить плов",
  "какая завтра погода в душанбе",
  "кто выиграл чемпионат по футболу",
  "как выучить английский язык",
  "сколько стоит билет на автобус",
  "посоветуй хороший фильм на вечер",
  "как починить кран на кухне",
  "какой курс доллара сегодня",
  "напиши стихотворение про любовь",
  "где купить дешёвый телефон",
];

function bestScore(query: string): number {
  const hits = getIndex(LANG).search(query, 1);
  return hits.length ? hits[0].score : 0;
}

function stats(scores: number[]) {
  const sorted = [...scores].sort((a, b) => a - b);
  const sum = scores.reduce((s, x) => s + x, 0);
  return {
    min: sorted[0],
    max: sorted[sorted.length - 1],
    avg: sum / scores.length,
    median: sorted[Math.floor(sorted.length / 2)],
  };
}

function bar(score: number): string {
  return "█".repeat(Math.round(score * 2));
}

function main() {
  console.log("\n=== ВОПРОСЫ, ОТВЕТ НА КОТОРЫЕ ЕСТЬ В БАЗЕ ===\n");
  const inScores: number[] = [];
  for (const q of IN_BASE) {
    const s = bestScore(q);
    inScores.push(s);
    console.log(`${s.toFixed(2).padStart(6)}  ${bar(s)}  ${q}`);
  }

  console.log("\n=== ПОСТОРОННИЕ ВОПРОСЫ ===\n");
  const offScores: number[] = [];
  for (const q of OFF_TOPIC) {
    const s = bestScore(q);
    offScores.push(s);
    console.log(`${s.toFixed(2).padStart(6)}  ${bar(s)}  ${q}`);
  }

  const inSt = stats(inScores);
  const offSt = stats(offScores);

  console.log("\n=== РАСПРЕДЕЛЕНИЕ ===\n");
  console.log(
    `«В базе»       n=${inScores.length}  min=${inSt.min.toFixed(2)}  median=${inSt.median.toFixed(2)}  avg=${inSt.avg.toFixed(2)}  max=${inSt.max.toFixed(2)}`
  );
  console.log(
    `«Посторонние»  n=${offScores.length}  min=${offSt.min.toFixed(2)}  median=${offSt.median.toFixed(2)}  avg=${offSt.avg.toFixed(2)}  max=${offSt.max.toFixed(2)}`
  );

  // Рекомендация: середина «провала» между наименьшей оценкой «в базе» и
  // наибольшей оценкой «посторонних». Если кластеры пересекаются, берём
  // значение чуть выше максимума посторонних, жертвуя полнотой ради точности.
  const gapLow = offSt.max;
  const gapHigh = inSt.min;
  const recommended =
    gapHigh > gapLow ? (gapLow + gapHigh) / 2 : offSt.max + 0.5;

  console.log("\n=== РЕКОМЕНДАЦИЯ ===\n");
  console.log(
    `Провал между кластерами: [${gapLow.toFixed(2)} … ${gapHigh.toFixed(2)}]`
  );
  console.log(`Рекомендуемый THRESHOLD ≈ ${recommended.toFixed(2)}`);
  console.log(
    gapHigh > gapLow
      ? "Кластеры разделяются чисто — порог попадает точно в провал.\n"
      : "Кластеры слегка пересекаются — порог смещён к точности (меньше ложных 'local').\n"
  );
}

main();
