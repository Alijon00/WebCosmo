// Общие типы ассистента «Mission Control AI».
// Здесь собраны структуры данных, которыми обмениваются все слои движка:
// нормализация → поиск BM25 → маршрутизация намерений → формирование ответа.

/** Языки, поддерживаемые сайтом и базой знаний. Совпадают с кодами i18n. */
export type Lang = "tg" | "ru" | "en";

/** Одна статья базы знаний. Формат единый для всех трёх языков. */
export interface KnowledgeDoc {
  /** Стабильный идентификатор (уникален в пределах языка). */
  id: string;
  /** Заголовок — при индексации получает буст ×2. */
  title: string;
  /** Теги/ключевые слова — при индексации получают буст ×1.5. */
  tags: string[];
  /** Тело статьи, 3–6 предложений простым языком. */
  body: string;
}

/** Откуда пришёл ответ ассистента. Отражается плашкой источника в UI. */
export type AnswerSource = "live" | "local" | "external" | "fallback";

/** Ближайшая тема-подсказка (кнопка) для fallback-ответа. */
export interface SuggestedTopic {
  id: string;
  title: string;
}

/** Итог работы движка — то, что показывает виджет. */
export interface AssistantAnswer {
  /** Текст ответа для пользователя. */
  text: string;
  /** Контур, который сформировал ответ. */
  source: AnswerSource;
  /** Заголовок статьи-источника (для source === 'local'). */
  docTitle?: string;
  /** Оценка релевантности лучшего документа (для отладки/порога). */
  score?: number;
  /** Кликабельные подсказки (для source === 'fallback'). */
  suggestions?: SuggestedTopic[];
}
