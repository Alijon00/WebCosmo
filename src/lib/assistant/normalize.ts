// ============================================================================
//  НОРМАЛИЗАЦИЯ ТЕКСТА  (Э1)
// ----------------------------------------------------------------------------
//  Приводит запрос пользователя и тексты базы знаний к единому виду, чтобы
//  поиск BM25 сравнивал их честно. Поддерживает три алфавита:
//    • латиница (en)
//    • кириллица (ru)
//    • таджикская кириллица с буквами ғ ӣ қ ӯ ҳ ҷ (tg)
//
//  Пайплайн одного текста:
//    normalize() → фразовая замена синонимов → tokenize() → стеммер → синонимы
//
//  Собственная реализация, без внешних NLP-библиотек.
// ============================================================================

import type { Lang } from "./types";
import synonymsData from "./synonyms.json";

// ---------------------------------------------------------------------------
// 1. Базовая нормализация: нижний регистр + снятие пунктуации.
// ---------------------------------------------------------------------------

/**
 * Приводит к нижнему регистру и заменяет всё, кроме букв и цифр, на пробел.
 * `\p{L}` (любая буква Unicode) покрывает латиницу, кириллицу И таджикские
 * буквы, поэтому специальный список ғ ӣ қ ӯ ҳ ҷ не нужен — они уже буквы.
 * Флаг `u` (Unicode) обязателен, иначе \p{...} не работает.
 */
export function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, "е") // ё→е: снимаем разнобой написания (ru)
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

// ---------------------------------------------------------------------------
// 2. Лёгкий стеммер: отбрасываем один словоизменительный суффикс.
// ---------------------------------------------------------------------------
//  Это НЕ полноценная лемматизация — намеренно простой алгоритм: находим
//  самый длинный подходящий суффикс из списка языка и отсекаем его, если
//  оставшаяся основа не короче MIN_STEM. Цель — чтобы «орбита», «орбиты»,
//  «орбитой» сходились к одной основе «орбит». Суффиксы отсортированы по
//  убыванию длины, чтобы «-ами» срабатывало раньше «-и».
// ---------------------------------------------------------------------------

const MIN_STEM = 3; // не укорачиваем основу короче 3 символов

// Порядок важен: длинные суффиксы проверяем первыми.
const SUFFIXES: Record<Lang, string[]> = {
  // Русские окончания существительных/прилагательных/глаголов.
  ru: [
    "ами", "ями", "ого", "его", "ыми", "ими", "ует", "уют", "ать", "ять",
    "ов", "ев", "ая", "яя", "ые", "ие", "ий", "ый", "ой", "ах", "ях",
    "ем", "ом", "ии", "ью", "ей", "у", "ю", "а", "я", "ы", "и", "е", "о",
  ],
  // Таджикские (кириллица) показатели множественного числа, изафета и связки.
  tg: ["хои", "ҳои", "хо", "ҳо", "анд", "ест", "ро", "ем", "ед", "и", "ӣ", "а"],
  // Английские окончания.
  en: ["ing", "edly", "ies", "ied", "ely", "es", "ed", "ly", "s"],
};

/** Отсекает один словоизменительный суффикс языка (если основа остаётся длинной). */
export function stem(token: string, lang: Lang): string {
  for (const suf of SUFFIXES[lang]) {
    if (token.length - suf.length >= MIN_STEM && token.endsWith(suf)) {
      return token.slice(0, -suf.length);
    }
  }
  return token;
}

// ---------------------------------------------------------------------------
// 3. Стоп-слова: очень частые слова, не несущие смысла для поиска.
// ---------------------------------------------------------------------------
const STOPWORDS = new Set<string>([
  // ru
  "и", "в", "во", "не", "на", "с", "со", "что", "как", "это", "по", "к",
  "у", "за", "от", "до", "из", "о", "об", "the", "a", "an",
  // en
  "of", "to", "in", "is", "are", "was", "for", "on", "at", "it", "and",
  // tg
  "ва", "дар", "ба", "аз", "ин", "он", "бо", "ки", "ҳам", "то",
]);

// ---------------------------------------------------------------------------
// 4. Словарь синонимов: строим карты один раз при загрузке модуля.
// ---------------------------------------------------------------------------
//  Идея: у каждой группы синонимов есть КАНОНИЧЕСКИЙ токен (производный от
//  первого элемента). Все прочие формы приводятся к нему, поэтому «истгоҳ»,
//  «мкс» и «space station» после нормализации становятся одним токеном.
//
//  Две карты:
//   • phraseMap  — для многословных синонимов (заменяются ДО токенизации),
//                  ключ = нормализованная фраза, значение = канонический токен
//                  (многословный канон склеивается через '_' в один токен).
//   • wordMap    — для однословных синонимов (применяются ПОСЛЕ стемминга),
//                  ключ = стем нормализованной формы, значение = канон.
// ---------------------------------------------------------------------------

interface SynonymGroups {
  groups: string[][];
}

const phraseMap = new Map<string, string>();
const wordMap = new Map<string, string>();

/** Канонический токен группы: многословный склеиваем через '_'. */
function canonicalToken(firstTerm: string, lang: Lang): string {
  const norm = normalize(firstTerm);
  const words = norm.split(" ");
  if (words.length > 1) return words.join("_");
  return stem(norm, lang);
}

(function buildSynonymMaps() {
  const { groups } = synonymsData as SynonymGroups;
  for (const group of groups) {
    if (!group.length) continue;
    // Канон строим на «нейтральном» стеммере ru — для однословных латинских
    // терминов это не мешает (латиница не совпадёт с ru-суффиксами не тронется).
    const canon = canonicalToken(group[0], "ru");
    for (const term of group) {
      const norm = normalize(term);
      const words = norm.split(" ");
      if (words.length > 1) {
        phraseMap.set(norm, canon);
      } else {
        // Кладём стем формы для каждого языка, чтобы совпадение не зависело
        // от того, на каком языке пришёл запрос.
        wordMap.set(stem(norm, "ru"), canon);
        wordMap.set(stem(norm, "tg"), canon);
        wordMap.set(stem(norm, "en"), canon);
        wordMap.set(norm, canon);
      }
    }
  }
})();

// Многословные фразы заменяем от длинных к коротким (чтобы «выход в открытый
// космос» сработал раньше, чем «космос»).
const phraseEntries = Array.from(phraseMap.entries()).sort(
  (a, b) => b[0].length - a[0].length
);

/** Заменяет многословные синонимы на их канонические токены. */
function applyPhraseSynonyms(normalized: string): string {
  let out = ` ${normalized} `;
  for (const [phrase, canon] of phraseEntries) {
    // Границы — пробелы (текст уже нормализован, пунктуации нет).
    out = out.split(` ${phrase} `).join(` ${canon} `);
  }
  return out.trim();
}

// ---------------------------------------------------------------------------
// 5. Токенизация: полный конвейер нормализации в массив токенов.
// ---------------------------------------------------------------------------

/**
 * Главная функция модуля: текст → массив нормализованных токенов.
 * Шаги: нормализация → многословные синонимы → разбиение → стоп-слова →
 * стемминг → однословные синонимы.
 */
export function tokenize(text: string, lang: Lang): string[] {
  const normalized = applyPhraseSynonyms(normalize(text));
  const raw = normalized.split(" ").filter(Boolean);

  const out: string[] = [];
  for (const token of raw) {
    if (STOPWORDS.has(token)) continue;
    // Канонические многословные токены уже содержат '_' — не трогаем.
    if (token.includes("_")) {
      out.push(token);
      continue;
    }
    const stemmed = stem(token, lang);
    out.push(wordMap.get(stemmed) ?? wordMap.get(token) ?? stemmed);
  }
  return out;
}
