/**
 * ПОРОГ РЕЛЕВАНТНОСТИ BM25.
 *
 * Если оценка лучшего документа >= THRESHOLD, мы уверены, что ответ есть в
 * локальной базе знаний, и отдаём его (source: 'local'). Если ниже — считаем,
 * что в базе точного ответа нет, и обращаемся к внешней модели, а при её
 * недоступности — к честному fallback.
 *
 * Значение подобрано ЭМПИРИЧЕСКИ скриптом scripts/tune-threshold.ts: он
 * прогоняет вопросы «в базе» и посторонние вопросы, смотрит на распределение
 * лучших оценок и выбирает порог в «провале» между двумя кластерами. Реальные
 * цифры и обоснование — в docs/ASSISTANT.md. Значение намеренно вынесено сюда
 * отдельной именованной константой, чтобы его было легко перенастроить.
 *
 * Прогон tune-threshold.ts (24 вопроса «в базе» + 10 посторонних, ru):
 *   «В базе»      → min 3.38, median 11.93, avg 11.99, max 20.65
 *   «Посторонние» → median 2.20, но два выброса по 4.49 (случайные совпадения
 *                   слов «доллар», «Душанбе», которые есть в статьях).
 * Порог 5.0 отсекает эти выбросы (4.49) и сохраняет 23 из 24 релевантных
 * вопросов (96% полноты). Единственный отсекаемый — «пристыковка» (3.38):
 * его слова слабо совпадают с базой, и он честно уходит во внешний контур.
 */
export const THRESHOLD = 5.0;

/** Сколько документов возвращает BM25 (и сколько тем показываем в fallback). */
export const TOP_K = 5;

/** Серверный эндпоинт резервного контура (Gemini). */
export const API_ENDPOINT = "/api/ask";

/** Таймаут запроса к внешней модели, мс (через AbortController). */
export const API_TIMEOUT_MS = 8000;
