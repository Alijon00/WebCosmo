// ============================================================================
//  ПОИСК BM25  (Э2)
// ----------------------------------------------------------------------------
//  Собственная реализация ранжирующей функции Okapi BM25 — БЕЗ библиотек
//  (никаких lunr / fuse / minisearch). Используется как основной («офлайн»)
//  контур ассистента: по запросу находит самые релевантные статьи базы знаний.
//
//  BM25 — это улучшенная версия TF-IDF. Она отвечает на вопрос: «насколько
//  документ D релевантен запросу Q?» и складывает вклад каждого слова запроса.
// ============================================================================

import type { KnowledgeDoc, Lang } from "./types";
import { tokenize } from "./normalize";

/** Результат поиска: документ и его итоговая оценка релевантности. */
export interface SearchHit {
  doc: KnowledgeDoc;
  score: number;
}

// ---------------------------------------------------------------------------
//  ГИПЕРПАРАМЕТРЫ BM25
// ---------------------------------------------------------------------------
//  k1 — «насыщение частотой терма» (term frequency saturation).
//       Управляет тем, как быстро перестаёт расти вклад слова при повторах.
//       При k1 → 0 частота почти не важна (важен сам факт наличия слова);
//       при большом k1 вклад растёт почти линейно. Классический диапазон
//       1.2–2.0; берём 1.5 — сбалансированное значение по умолчанию из
//       литературы (TREC): у нас короткие статьи, и мы не хотим, чтобы одно
//       слово, повторённое 5 раз, задавило все остальные.
//
//  b  — «сила нормализации по длине» (length normalization). При b = 1 длина
//       документа учитывается полностью (длинные документы штрафуются, ведь у
//       них больше шансов случайно содержать слово), при b = 0 — не
//       учитывается вовсе. Стандартное значение 0.75: наши статьи разной длины
//       (3–6 предложений), и умеренный штраф не даёт длинным текстам
//       несправедливого преимущества.
// ---------------------------------------------------------------------------
const K1 = 1.5;
const B = 0.75;

// Бусты полей: совпадение в заголовке/тегах важнее совпадения в теле.
const TITLE_BOOST = 2.0; // ×2 за попадание в title
const TAGS_BOOST = 1.5; // ×1.5 за попадание в tags

/** Внутреннее представление проиндексированного документа. */
interface IndexedDoc {
  doc: KnowledgeDoc;
  /** Частоты термов в теле: term → сколько раз встретился. */
  tf: Map<string, number>;
  /** Множество термов заголовка (для буста ×2). */
  titleTerms: Set<string>;
  /** Множество термов тегов (для буста ×1.5). */
  tagTerms: Set<string>;
  /** Длина документа в токенах (тело) — знаменатель нормализации по длине. */
  length: number;
}

export class BM25Index {
  private lang: Lang;
  private docs: IndexedDoc[] = [];
  /** Document frequency: term → в скольких документах он встречается. */
  private df = new Map<string, number>();
  /** Средняя длина документа по корпусу — база для нормализации. */
  private avgDocLen = 0;
  /** Число документов в корпусе (N в формуле IDF). */
  private N = 0;

  constructor(documents: KnowledgeDoc[], lang: Lang) {
    this.lang = lang;
    this.build(documents);
  }

  // -------------------------------------------------------------------------
  //  ИНДЕКСАЦИЯ. Считается один раз; результат мемоизируется в полях класса.
  //  Здесь мы заранее вычисляем всё, что не зависит от запроса: tf, df,
  //  длины и среднюю длину. На запросе останется лишь сложить вклад термов.
  // -------------------------------------------------------------------------
  private build(documents: KnowledgeDoc[]): void {
    this.docs = [];
    this.df = new Map();
    let totalLen = 0;

    for (const doc of documents) {
      const bodyTokens = tokenize(doc.body, this.lang);
      const titleTerms = new Set(tokenize(doc.title, this.lang));
      const tagTerms = new Set(tokenize(doc.tags.join(" "), this.lang));

      // Частоты термов в теле документа.
      const tf = new Map<string, number>();
      for (const tok of bodyTokens) {
        tf.set(tok, (tf.get(tok) ?? 0) + 1);
      }

      // Document frequency считаем по ОБЪЕДИНЕНИЮ уникальных термов всех полей:
      // если слово есть хоть в заголовке/тегах/теле — документ содержит его.
      const uniqueTerms = new Set<string>([
        ...tf.keys(),
        ...titleTerms,
        ...tagTerms,
      ]);
      for (const term of uniqueTerms) {
        this.df.set(term, (this.df.get(term) ?? 0) + 1);
      }

      const length = bodyTokens.length;
      totalLen += length;
      this.docs.push({ doc, tf, titleTerms, tagTerms, length });
    }

    this.N = this.docs.length;
    this.avgDocLen = this.N > 0 ? totalLen / this.N : 0;
  }

  /**
   * Пересобрать индекс с нуля — для динамического добавления документов
   * (например, из админ-панели знаний во время демонстрации).
   */
  reindex(documents: KnowledgeDoc[]): void {
    this.build(documents);
  }

  /** Число документов в индексе. */
  get size(): number {
    return this.N;
  }

  // -------------------------------------------------------------------------
  //  IDF — inverse document frequency (обратная документная частота).
  //
  //     idf(term) = log( 1 + (N - df + 0.5) / (df + 0.5) )
  //
  //  Смысл: редкое слово (маленький df) несёт больше информации о релевантности,
  //  чем частое. «+0.5» — сглаживание (не даём нулей/бесконечностей), а «1 +»
  //  снаружи логарифма гарантирует idf >= 0 даже для слова, встречающегося
  //  почти во всех документах (в классическом BM25 такое слово могло получить
  //  отрицательный вес). N — размер корпуса, df — в скольких документах слово.
  // -------------------------------------------------------------------------
  private idf(term: string): number {
    const df = this.df.get(term) ?? 0;
    return Math.log(1 + (this.N - df + 0.5) / (df + 0.5));
  }

  // -------------------------------------------------------------------------
  //  ПОИСК. Возвращает topK документов, отсортированных по убыванию оценки.
  //
  //  Итоговая оценка документа — сумма по всем термам запроса:
  //
  //     score(D, Q) = Σ_term  idf(term) · ( tf · (k1 + 1) )
  //                                      -----------------------------------
  //                                      tf + k1 · (1 - b + b · |D| / avgDL)
  //
  //  где tf — частота терма в документе (с учётом бустов полей),
  //      |D| — длина документа, avgDL — средняя длина по корпусу.
  //
  //  Числитель `tf · (k1+1)` растёт с частотой, но знаменатель `tf + k1·(...)`
  //  ограничивает этот рост — отсюда «насыщение»: 10-е вхождение слова даёт
  //  почти столько же, сколько 9-е. Множитель `(1 - b + b·|D|/avgDL)` и есть
  //  нормализация по длине: документ длиннее среднего получает знаменатель
  //  больше 1 (штраф), короче среднего — меньше 1 (бонус).
  // -------------------------------------------------------------------------
  search(query: string, topK = 5): SearchHit[] {
    const qTerms = tokenize(query, this.lang);
    if (qTerms.length === 0 || this.N === 0) return [];

    // Уникальные термы запроса — повтор слова в запросе не должен считаться дважды.
    const uniqueQ = Array.from(new Set(qTerms));

    const hits: SearchHit[] = [];
    for (const indexed of this.docs) {
      let score = 0;
      for (const term of uniqueQ) {
        // Эффективная частота терма в документе = частота в теле
        // ПЛЮС бонус за присутствие в заголовке (×2) и тегах (×1.5).
        // Так совпадение по ключевым полям поднимает документ выше.
        let tf = indexed.tf.get(term) ?? 0;
        if (indexed.titleTerms.has(term)) tf += TITLE_BOOST;
        if (indexed.tagTerms.has(term)) tf += TAGS_BOOST;
        if (tf === 0) continue; // терма нет в документе — вклад нулевой

        const idf = this.idf(term);
        const numerator = tf * (K1 + 1);
        const denominator =
          tf + K1 * (1 - B + B * (indexed.length / (this.avgDocLen || 1)));
        score += idf * (numerator / denominator);
      }
      if (score > 0) hits.push({ doc: indexed.doc, score });
    }

    // Сортируем по убыванию оценки и берём верхние topK.
    hits.sort((a, b) => b.score - a.score);
    return hits.slice(0, topK);
  }
}
